# Descenders: rows 8-9 for the few glyphs that need them.
DESCENDERS: dict[str, str] = {
    "g": "....#/.###.",
    "j": "#..#./.##..",
    "p": "#..../#....",
    "q": "....#/....#",
    "y": "....#/.###.",
    ",": ".#.../.....",
    ";": ".#.../.....",
}

ORDER = list(GLYPHS.keys())


def _draw_glyph(canvas: Canvas, ch: str, ox: int, oy: int, color: RGBA, scale: int) -> None:
    rows = GLYPHS[ch].split("/")
    rows += DESCENDERS.get(ch, "...../.....").split("/")
    for ry, row in enumerate(rows):
        for rx, cell in enumerate(row):
            if cell != "#":
                continue
            for sy in range(scale):
                for sx in range(scale):
                    canvas.set(ox + rx * scale + sx, oy + ry * scale + sy, color)


def build(scale: int = 1, color: RGBA = (255, 255, 255, 255)) -> tuple[Canvas, str]:
    """Returns (atlas, fnt_text) for one integer scale."""
    cols = 16
    rows = (len(ORDER) + cols - 1) // cols
    cw, chh = CELL_W * scale, CELL_H * scale
    atlas = Canvas(cols * cw, rows * chh)

    lines = [
        f'info face="Nightbane" size={BASELINE * scale} bold=0 italic=0 charset="" '
        f"unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0",
        f"common lineHeight={(CELL_H + 1) * scale} base={BASELINE * scale} "
        f"scaleW={atlas.w} scaleH={atlas.h} pages=1 packed=0",
        f'page id=0 file="nightbane_{scale}x.png"',
        f"chars count={len(ORDER)}",
    ]

    for i, ch in enumerate(ORDER):
        gx, gy = (i % cols) * cw, (i // cols) * chh
        _draw_glyph(atlas, ch, gx, gy, color, scale)
        lines.append(
            f"char id={ord(ch)} x={gx} y={gy} width={cw} height={chh} "
            f"xoffset=0 yoffset=0 xadvance={cw} page=0 chnl=15"
        )

    return atlas, "\n".join(lines) + "\n"


SIZES = (1, 2, 3, 4)


def export(root: Path) -> list[int]:
    """Writes one atlas + .fnt per scale under Assets/Fonts."""
    out = root / "Assets" / "Fonts"
    out.mkdir(parents=True, exist_ok=True)
    for scale in SIZES:
        atlas, fnt = build(scale)
        atlas.save(out / f"nightbane_{scale}x.png")
        (out / f"nightbane_{scale}x.fnt").write_text(fnt)
    return [BASELINE * s for s in SIZES]
